"""
Goal 1: 8-bit network (ideal sigmoid)    vs  ideal float network
Goal 2: 8-bit network + OUR sigmoid      vs  ideal float network
Network: Flatten -> Linear(784, 64) -> Sigmoid -> Linear(64, 10)   (Fashion-MNIST)
"""

import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
import torchvision
import torchvision.transforms as transforms
import matplotlib.pyplot as plt

HIDDEN = 64
EPOCHS = 5


# 1. The float network (same as our original script)
class FashionMLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.flatten = nn.Flatten()
        self.fc1 = nn.Linear(28 * 28, HIDDEN)
        self.act = nn.Sigmoid()
        self.fc2 = nn.Linear(HIDDEN, 10)

    def forward(self, x):
        return self.fc2(self.act(self.fc1(self.flatten(x))))


# 2. The two sigmoids used inside the 8-bit network
#    Both take the layer-1 accumulator (integer) and return Q1.7 (0..128)
def ideal_sigmoid_8bit(acc1, acc_frac_bits):
    """Exact sigmoid of the exact accumulator value; only the output is rounded to 8 bits."""
    x = acc1 / 2.0 ** acc_frac_bits
    return np.rint(128.0 / (1.0 + np.exp(-x))).astype(np.int64)


def our_sigmoid_8bit(acc1, acc_frac_bits):
    """Our hardware sigmoid (sigmoid_57): requantize to Q3.4, then PWL with shifts."""
    # Requantize: accumulator -> Q3.4 (4 fraction bits), round half up, saturate to +-127
    s = acc_frac_bits - 4
    z = np.clip((acc1 + (1 << (s - 1))) >> s, -127, 127)

    # Same logic as our BitAccurateSigmoid
    a = np.abs(z)
    idx = sum((a >= t).astype(np.int64) for t in (11, 24, 36, 48, 64, 80))
    a10 = a << 6
    slope = np.select(
        [idx == 0, idx == 1, idx == 2, idx == 3, idx == 4, idx == 5],
        [a10 >> 2, (a10 >> 3) + (a10 >> 4), a10 >> 3, a10 >> 4, a10 >> 5, a10 >> 6],
        default=0)
    intercept = np.array([64, 69, 80, 98, 110, 118, 128]) << 3
    sigma_abs = (slope + intercept[idx]) >> 3
    return np.where(z < 0, 128 - sigma_abs, sigma_abs)


# 3. Convert the trained float network to 8-bit integers
def to_int8(w):
    """Power-of-2 scale: largest F so that max|w| * 2^F fits in int8."""
    F = int(np.floor(np.log2(127 / np.max(np.abs(w)))))
    return np.clip(np.round(w * 2 ** F), -128, 127).astype(np.int64), F


def quantize(model):
    w1, F1 = to_int8(model.fc1.weight.detach().numpy())
    w2, F2 = to_int8(model.fc2.weight.detach().numpy())
    # Bias is stored in the accumulator's scale: inputs have 7 fraction bits, weights F
    b1 = np.round(model.fc1.bias.detach().numpy() * 2 ** (7 + F1)).astype(np.int64)
    b2 = np.round(model.fc2.bias.detach().numpy() * 2 ** (7 + F2)).astype(np.int64)
    return w1, b1, F1, w2, b2, F2


def run_8bit(pixels, q, sigmoid_8bit):
    """The whole network in integers, exactly like the hardware."""
    w1, b1, F1, w2, b2, F2 = q
    x = (256 * pixels.astype(np.int64) + 255) // 510        # pixel 0..255 -> 0..128
    acc1 = x @ w1.T + b1                                    # Linear 1 (integer MAC)
    y1 = sigmoid_8bit(acc1, 7 + F1)                         # Sigmoid -> 0..128
    acc2 = y1 @ w2.T + b2                                   # Linear 2 (integer MAC)
    return np.argmax(acc2, axis=1)                          # predicted class


# 4. Main
def main():
    torch.manual_seed(0)
    tf = transforms.ToTensor()
    train_ds = torchvision.datasets.FashionMNIST("./data", train=True, download=True, transform=tf)
    test_ds = torchvision.datasets.FashionMNIST("./data", train=False, download=True, transform=tf)
    train_loader = torch.utils.data.DataLoader(train_ds, batch_size=64, shuffle=True)

    # Train the float network
    model = FashionMLP()
    optimizer = optim.Adam(model.parameters(), lr=0.001)
    criterion = nn.CrossEntropyLoss()
    for epoch in range(EPOCHS):
        for images, labels in train_loader:
            optimizer.zero_grad()
            criterion(model(images), labels).backward()
            optimizer.step()
        print(f"Epoch {epoch + 1}/{EPOCHS} done")
    model.eval()

    # Test set as raw bytes (0..255) and labels
    pixels = test_ds.data.numpy().reshape(-1, 784)
    labels = test_ds.targets.numpy()

    # Ideal: float network, exact sigmoid
    with torch.no_grad():
        float_pred = model(test_ds.data.float().unsqueeze(1) / 255.0).argmax(dim=1).numpy()
    acc_ideal = 100 * np.mean(float_pred == labels)

    # Goal 1: 8-bit network, ideal sigmoid
    q = quantize(model)
    acc_8bit = 100 * np.mean(run_8bit(pixels, q, ideal_sigmoid_8bit) == labels)

    # Goal 2: 8-bit network, our sigmoid
    acc_8bit_ours = 100 * np.mean(run_8bit(pixels, q, our_sigmoid_8bit) == labels)

    print("\n=== Results (Fashion-MNIST test set, 10,000 images) ===")
    print(f"Ideal (float, exact sigmoid)        : {acc_ideal:.2f}%")
    print(f"Goal 1: 8-bit, ideal sigmoid         : {acc_8bit:.2f}%   (gap {acc_8bit - acc_ideal:+.2f})")
    print(f"Goal 2: 8-bit, our sigmoid           : {acc_8bit_ours:.2f}%   (gap {acc_8bit_ours - acc_ideal:+.2f})")

    # Graph
    names = ["Ideal\n(float)", "8-bit\n(ideal sigmoid)", "8-bit\n(our sigmoid)"]
    values = [acc_ideal, acc_8bit, acc_8bit_ours]
    plt.figure(figsize=(8, 6))
    bars = plt.bar(names, values, color=["#FFD1DC", "#AEC6CF", "#B19CD9"], edgecolor="black")
    for bar in bars:
        plt.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 1.5,
                 f"{bar.get_height():.2f}%", ha="center", fontweight="bold")
    plt.ylim(0, 100)
    plt.ylabel("Test Accuracy (%)", fontsize=12)
    plt.title(f"Fashion-MNIST (784-{HIDDEN}-10): 8-bit vs Ideal", fontsize=14, fontweight="bold")
    plt.tight_layout()
    plt.savefig("quant_vs_ideal.png", dpi=300)
    plt.show()


if __name__ == "__main__":
    main()